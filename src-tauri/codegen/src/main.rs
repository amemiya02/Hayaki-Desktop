//! Generates TypeScript from the descriptor set written by the core's build.
//!
//! Usage: hayaki_codegen <descriptors.bin> <output-folder>
//!
//! Writes `core.ts` into the folder: one typed async function for every core
//! method, addressed by the service and method numbers the core dispatches
//! on. The numbers come from upstream's own `anki_proto_gen::get_services`,
//! the helper the core's dispatcher is generated from, so they always match
//! the built library. Nothing is numbered by hand.
//!
//! Message types are the ones `protoc-gen-es` (v2) writes for the core's
//! `.proto` files into `../proto/`.

use std::collections::BTreeMap;
use std::collections::BTreeSet;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anki_proto_gen::get_services;
use anki_proto_gen::BackendService;
use anki_proto_gen::Method;
use anyhow::Context;
use anyhow::Result;
use prost_reflect::DescriptorPool;
use prost_reflect::MessageDescriptor;

const HEADER: &str = "// Generated by src-tauri/codegen from the Anki core's descriptor set. Do not edit.\n\
                      // Regenerate with `npm run core:gen`.\n";

fn main() -> Result<()> {
    let args: Vec<String> = env::args().collect();
    let [_, descriptors, output] = args.as_slice() else {
        anyhow::bail!("usage: hayaki_codegen <descriptors.bin> <output-folder>");
    };
    let bytes = fs::read(descriptors).with_context(|| format!("reading {descriptors}"))?;
    let pool = DescriptorPool::decode(bytes.as_slice()).context("decoding descriptor set")?;
    let (_, services) = get_services(&pool);
    let output = Path::new(output);
    fs::create_dir_all(output).with_context(|| format!("creating {}", output.display()))?;
    write_if_changed(&output.join("core.ts"), &render(&services)?)?;
    Ok(())
}

fn write_if_changed(path: &Path, contents: &str) -> Result<()> {
    if fs::read_to_string(path).ok().as_deref() != Some(contents) {
        fs::write(path, contents).with_context(|| format!("writing {}", path.display()))?;
    }
    Ok(())
}

/// How deep `anki.collection.OpChanges` sits in a response, following field 1.
/// Mirrors upstream's TypeScript generator so the same responses notify the
/// interface of changes.
fn op_changes_level(message: &MessageDescriptor, level: u8) -> u8 {
    if message.full_name() == "anki.collection.OpChanges" {
        return level;
    }
    match message.get_field(1).and_then(|f| f.kind().as_message().cloned()) {
        Some(inner) if level < 3 => op_changes_level(&inner, level + 1),
        _ => 0,
    }
}

/// `anki/import_export.proto` becomes `import_export`.
fn module_alias(message: &MessageDescriptor) -> String {
    let file = message.parent_file();
    let name = file.name();
    name.trim_start_matches("anki/")
        .trim_end_matches(".proto")
        .replace('/', "_")
}

fn module_path(message: &MessageDescriptor) -> String {
    let file = message.parent_file();
    format!("../proto/{}", file.name().trim_end_matches(".proto")) + "_pb"
}

/// The name protoc-gen-es gives a message: nested names joined by `_`.
/// `anki.import_export.ImportResponse.Log` becomes `ImportResponse_Log`.
fn es_name(message: &MessageDescriptor) -> String {
    let package = message.package_name();
    message
        .full_name()
        .strip_prefix(package)
        .and_then(|rest| rest.strip_prefix('.'))
        .unwrap_or(message.full_name())
        .replace('.', "_")
}

fn lower_camel(name: &str) -> String {
    let mut chars = name.chars();
    match chars.next() {
        Some(first) => first.to_lowercase().chain(chars).collect(),
        None => String::new(),
    }
}

fn render(services: &[BackendService]) -> Result<String> {
    let mut by_name: BTreeMap<String, &str> = BTreeMap::new();
    let mut imports: BTreeMap<String, String> = BTreeMap::new();
    let mut body = String::new();
    let mut table = String::new();

    for service in services {
        for method in service.all_methods() {
            let name = lower_camel(method.proto.name());
            if let Some(other) = by_name.insert(name.clone(), &service.name) {
                anyhow::bail!("core method {name} exists in both {other} and {}", service.name);
            }
            render_method(&mut body, &mut imports, service, method, &name);
            writeln!(
                table,
                "  {name}: [{}, {}],",
                service.index, method.index
            )
            .unwrap();
        }
    }

    let mut out = String::from(HEADER);
    out.push_str("/* eslint-disable */\n\n");
    out.push_str("import type { MessageInitShape } from \"@bufbuild/protobuf\";\n");
    out.push_str("import { call, type CallOptions } from \"../transport\";\n");
    let mut seen = BTreeSet::new();
    for (alias, path) in &imports {
        if seen.insert(alias) {
            writeln!(out, "import * as {alias} from \"{path}\";").unwrap();
        }
    }
    out.push_str("\n/** Service and method numbers of every core method. */\n");
    out.push_str("export const methodNumbers = {\n");
    out.push_str(&table);
    out.push_str("} as const;\n\n");
    out.push_str(&body);
    Ok(out)
}

fn render_method(
    out: &mut String,
    imports: &mut BTreeMap<String, String>,
    service: &BackendService,
    method: &Method,
    name: &str,
) {
    let input = method.proto.input();
    let output = method.proto.output();
    for message in [&input, &output] {
        imports.insert(format!("pb_{}", module_alias(message)), module_path(message));
    }
    let in_ref = format!("pb_{}.{}", module_alias(&input), es_name(&input));
    let out_ref = format!("pb_{}.{}", module_alias(&output), es_name(&output));
    let op_changes = op_changes_level(&output, 1);

    if let Some(comments) = &method.comments {
        out.push_str("/**\n");
        for line in comments.lines() {
            writeln!(out, " * {}", line.trim()).unwrap();
        }
        writeln!(out, " *\n * Core method `{}`.\n */", method.proto.full_name()).unwrap();
    } else {
        writeln!(out, "/** Core method `{}`. */", method.proto.full_name()).unwrap();
    }

    let (param, arg) = if method.input().is_some() {
        (
            format!("input: MessageInitShape<typeof {in_ref}Schema>, "),
            "input",
        )
    } else {
        (String::new(), "{}")
    };
    let (ret, unwrap) = if method.output().is_some() {
        (out_ref.clone(), "")
    } else {
        ("void".to_string(), "")
    };
    let _ = unwrap;
    writeln!(
        out,
        "export function {name}({param}options?: CallOptions): Promise<{ret}> {{\n  \
         return call({service}, {method_index}, {in_ref}Schema, {arg}, {out_ref}Schema, {op_changes}, options) as Promise<{ret}>;\n}}\n",
        service = service.index,
        method_index = method.index,
    )
    .unwrap();
}
